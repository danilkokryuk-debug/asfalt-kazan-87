function pickRandom(S, d) {
  const pool = Object.values(EV).filter(e => e.random && e.random(S, d));
  let r = Math.random() * pool.reduce((a, e) => a + e.weight, 0);
  for (const e of pool) if ((r -= e.weight) < 0) return e.id;
  return 'r_quiet';
}

