function slangSeen(text) {
  if (typeof __TEST !== 'undefined' || !text) return;
  const m = metaGet(); m.slang = m.slang || [];
  const hit = SLANG.find(([w, re]) => !m.slang.includes(w) && re.test(text)); if (!hit) return;
  m.slang.push(hit[0]); metaPut(m);
  if (typeof toast === 'function') toast(`Новое слово в словаре: «${hit[0]}»`);
}
