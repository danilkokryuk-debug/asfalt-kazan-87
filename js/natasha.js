// Наташа: свидания, ссоры, соперник, её день рождения, знакомство с родителями.
// Кнопка «Позвать гулять» — на экране героя. Свидание занимает время, раз в день.
// Близость — только когда обоим уже есть восемнадцать (с осени 1990-го), и показана намёком: тёплое окно в размытии, потом утро.
const N_ADULT = () => typeof dayNum === 'function' ? dayNum(1990, 9, 1) : 1e9;
const nFree = S => !S.flags.n_last || S.day - S.flags.n_last >= 1;   // раз в день
const nOk = S => S.flags.met_natasha && !S.flags.natasha_gone && !S.flags.natasha_lost && !S.ending;
const nStage = S => !nOk(S) ? 0 : S.flags.n_noch ? 6 : S.flags.n_roditeli ? 5 : S.flags.n_para ? 4 : S.flags.kiss ? 3 : S.rel.natasha >= 35 ? 2 : 1;
const N_STAGES = ['', 'Знакомые', 'Гуляете вместе', 'Был поцелуй', 'Встречаетесь', 'Её родители тебя знают', 'Вы вместе по-настоящему'];
function natHtml(S) {
  if (!nOk(S)) return '';
  const can = S.ap > 0 && nFree(S);
  return `<div class="nat"><div><span>💌 Наташа</span><b>${N_STAGES[nStage(S)]}</b><i style="width:${S.rel.natasha}%"></i></div>
    <button class="btn main" onclick="natDate()" ${can ? '' : 'disabled'}>${can ? 'Позвать гулять' : S.ap > 0 ? 'Сегодня уже виделись' : 'Поздно, завтра'}</button></div>`;
}
// Выбор свидания: сначала вехи отношений, потом обычные прогулки
function natDate() {
  if (!nOk(S)) return;
  const st = nStage(S), f = S.flags, adult = typeof adultPair === 'function' ? adultPair(S) : S.day >= N_ADULT();
  let id = null;
  if (st >= 3 && !f.n_para && S.rel.natasha >= 55) id = 'n_para';
  else if (st >= 4 && !f.n_roditeli && S.rel.natasha >= 65) id = 'n_roditeli';
  else if (st >= 5 && adult && !f.n_noch && S.rel.natasha >= 80 && S.st.lyub >= 70) id = 'n_vecher';
  else if (st >= 2 && !f.n_dr && S.rel.natasha >= 45) id = 'n_dr';
  else if (st >= 3 && !f.n_sopernik && Math.random() < 0.3) id = 'n_sopernik';
  else if (st >= 2 && S.st.sovest < 35 && Math.random() < 0.35) id = 'n_ssora';
  else id = pick(['n_kino', 'n_katok', 'n_krysha', 'n_park', 'n_naberezh', 'n_disco'].filter(x => x !== f.n_prev));
  f.n_prev = id; S.flags.n_last = S.day;
  advanceTime(ACT_MIN); play(id);
}
